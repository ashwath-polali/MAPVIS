export function chromaticityAt(kelvin) {
  const k = Math.max(KELVIN_MIN, Math.min(KELVIN_MAX, kelvin))
  const pos = (k - KELVIN_MIN) / KELVIN_STEP
  const i = Math.min(Math.floor(pos), (PLANCKIAN.length >> 1) - 2)
  const t = pos - i
  const x0 = PLANCKIAN[i * 2]
  const y0 = PLANCKIAN[i * 2 + 1]
  const x1 = PLANCKIAN[i * 2 + 2]
  const y1 = PLANCKIAN[i * 2 + 3]
  return [x0 + (x1 - x0) * t, y0 + (y1 - y0) * t]
}
